// Writes the FPGA top level of a plan (plan.ts) in Verilog or VHDL (evo ToplevelHdlGeneratorFactory): the ports,
// the signal adaptations (inversion of active-low pins, constants), the clock dividers, the design instance, and
// the LED array / 7-segment drivers, followed by the helper modules the top level uses.
import { driverModule, helperModuleText, scanningCounter, SEGMENT_PORTS, type HdlLang, type HelperModule } from './drivers';
import { addressBitsFor, bitsFor, driverSignals, FPGA_CLOCK, type DesignPortPlan, type DriverPlan, type TopLevelPlan } from './plan';

export interface WrapperOptions {
  /** Comment lines for the file header (board, warnings ...); written as is after the comment marker */
  header?: string[];
}

/** VHDL writes vector bits with () */
function sig(text: string, lang: HdlLang): string {
  return lang === 'vhdl' ? text.replace(/\[(\d+)\]$/, '($1)') : text;
}

function vecType(width: number): string {
  return width > 1 ? `std_logic_vector(${width - 1} downto 0)` : 'std_logic';
}

function bitOf(name: string, width: number, bit: number, lang: HdlLang): string {
  if (width <= 1) return name;
  return lang === 'verilog' ? `${name}[${bit}]` : `${name}(${bit})`;
}

const zero = (lang: HdlLang) => (lang === 'verilog' ? "1'b0" : "'0'");
const one = (lang: HdlLang) => (lang === 'verilog' ? "1'b1" : "'1'");
const not = (x: string, lang: HdlLang) => (lang === 'verilog' ? `~${x}` : `not ${x}`);

/** The top-level file: the top level and the helper modules it needs (the design module goes in its own file) */
export function writeTopLevel(plan: TopLevelPlan, lang: HdlLang, options: WrapperOptions = {}): string {
  const c = lang === 'verilog' ? '//' : '--';
  const helpers = new Set<HelperModule>();
  if (plan.clocks.some((k) => k.halfPeriod > 0)) helpers.add('LogisimClockDivider');
  for (const d of plan.drivers) helpers.add(driverModule(d));

  const out: string[] = [
    `${c} =============================================================================`,
    `${c} FPGA top level generated by LogicDesign Studio`,
    `${c} Top level: ${plan.name}, design: ${plan.designName}`,
    ...(options.header ?? []).map((h) => (h ? `${c} ${h}` : c)),
    `${c} =============================================================================`,
    '',
  ];
  if (lang === 'verilog') out.push('`timescale 1ns / 1ps', '');
  // Helpers first: a VHDL entity must be analysed before the top level instantiates it
  for (const h of helpers) out.push(helperModuleText(h, lang), '');
  out.push(...(lang === 'verilog' ? topVerilog(plan) : topVhdl(plan)), '');
  return out.join('\n');
}

// --- shared pieces ---------------------------------------------------------------------------------------------

/** Assignments of the signal adaptations: design input bits from ports / constants, ports from design output bits */
function adaptations(plan: TopLevelPlan, lang: HdlLang): string[] {
  const lines: string[] = [];
  const assign = (dst: string, src: string) => lines.push(lang === 'verilog' ? `  assign ${dst} = ${src};` : `  ${dst} <= ${src};`);
  for (const p of plan.designPorts) {
    if (p.clock !== undefined || p.dir === 'inout') continue;
    p.bits.forEach((b, bit) => {
      const s = bitOf(`s_${p.name}`, p.width, bit, lang);
      if (b.kind === 'input') {
        if (b.source.kind === 'const') assign(s, b.source.value ? one(lang) : zero(lang));
        else assign(s, b.source.invert ? not(b.source.port, lang) : b.source.port);
      } else if (b.kind === 'output') assign(b.port, b.invert ? not(s, lang) : s);
    });
  }
  return lines;
}

/** Assignments of the drivers' inputs (an LED / segment nothing is mapped on is off) */
function driverInputs(d: DriverPlan, lang: HdlLang): string[] {
  const lines: string[] = [];
  const assign = (dst: string, src: string) => lines.push(lang === 'verilog' ? `  assign ${dst} = ${src};` : `  ${dst} <= ${src};`);
  const [first, green, blue] = driverSignals(d);
  if (d.kind === 'scanning') {
    d.segments.forEach((s, i) => assign(bitOf(first, d.segments.length, i, lang), s ? sig(s, lang) : zero(lang)));
  } else if (d.drive.startsWith('rgb')) {
    const n = d.leds.length;
    d.leds.forEach((led, i) => {
      assign(bitOf(first, n, i, lang), sig(led.red ?? led.mono ?? '', lang) || zero(lang));
      assign(bitOf(green, n, i, lang), sig(led.green ?? led.mono ?? '', lang) || zero(lang));
      assign(bitOf(blue, n, i, lang), sig(led.blue ?? led.mono ?? '', lang) || zero(lang));
    });
  } else {
    const n = d.leds.length;
    d.leds.forEach((led, i) => assign(bitOf(first, n, i, lang), led.mono ? sig(led.mono, lang) : zero(lang)));
  }
  return lines;
}

/** Width of each driver input signal */
function driverSignalWidth(d: DriverPlan): number {
  return d.kind === 'scanning' ? d.segments.length : d.leds.length;
}

/** Generic values and port connections of a driver instance */
function driverInstance(d: DriverPlan, oscillatorHz: number): { generics: [string, number][]; ports: [string, string | null][] } {
  const scan = scanningCounter(oscillatorHz);
  if (d.kind === 'scanning') {
    const decoded = d.drive === 'decoded';
    const control = decoded ? Math.max(1, d.selectWidth) : Math.max(1, addressBitsFor(d.digits));
    const generics: [string, number][] = [
      ['nrOfDigits', d.digits],
      ['nrOfControl', control],
      ['activeLow', d.activeLow ? 1 : 0],
      ...(decoded ? [] : ([['activeLowSelectPins', d.drive === 'activeLow' ? 1 : 0]] as [string, number][])),
      ['nrOfScanningCounterBits', scan.bits],
      ['scanningCounterReloadValue', scan.reload],
    ];
    const ports: [string, string | null][] = [
      ['fpgaGlobalClock', FPGA_CLOCK],
      ['allSegments', `s_scanningSevenSegSegments${d.id}`],
      [decoded ? 'digitDecodedSelect' : 'digitSelect', d.selectWidth > 0 ? `Displ${d.id}Select` : null],
      ...SEGMENT_PORTS.map((s, i) => [s, `Displ${d.id}_${['a', 'b', 'c', 'd', 'e', 'f', 'g', 'dp'][i]}`] as [string, string]),
    ];
    return { generics, ports };
  }
  const [r, g, b] = driverSignals(d);
  const rgb = d.drive.startsWith('rgb');
  const colors = rgb ? (['Red', 'Green', 'Blue'] as const) : ([''] as const);
  const ins = rgb ? [r, g, b] : [r];
  if (d.drive.endsWith('Default')) {
    return {
      generics: [
        ['nrOfLeds', d.rows * d.columns],
        ['activeLow', d.activeLow ? 1 : 0],
      ],
      ports: [
        ...colors.map((c, i) => [`internal${c}Leds`, ins[i]] as [string, string]),
        ...colors.map((c) => [`external${c}Leds`, `external${c}Leds${d.id}`] as [string, string]),
      ],
    };
  }
  const row = d.drive.includes('Row');
  const addr = row ? 'rowAddress' : 'columnAddress';
  const outBase = row ? 'column' : 'row';
  return {
    generics: [
      ['nrOfRows', d.rows],
      ['nrOfColumns', d.columns],
      [row ? 'nrOfRowAddressBits' : 'nrOfColumnAddressBits', Math.max(1, d.addressBits)],
      ['activeLow', d.activeLow ? 1 : 0],
      ['nrOfScanningCounterBits', scan.bits],
      ['scanningCounterReloadValue', scan.reload],
    ],
    ports: [
      ['fpgaGlobalClock', FPGA_CLOCK],
      ...colors.map((c, i) => [`internal${c}Leds`, ins[i]] as [string, string]),
      [addr, d.addressBits > 0 ? `${addr}${d.id}` : null],
      ...colors.map((c) => [`${outBase}${c}Leds`, `${outBase}${c}Leds${d.id}`] as [string, string]),
    ],
  };
}

/** Connections of the design instance: port -> actual (Verilog: an expression; VHDL: one entry per bit for inout) */
function designConnections(plan: TopLevelPlan, lang: HdlLang): string[] {
  const conns: string[] = [];
  for (const p of plan.designPorts) {
    if (p.clock !== undefined) {
      conns.push(lang === 'verilog' ? `.${p.name}(${clockNet(plan, p)})` : `${p.name} => ${clockNet(plan, p)}`);
    } else if (p.dir === 'inout') {
      const actual = (bit: number) => {
        const b = p.bits[bit];
        return b.kind === 'inout' ? b.port : bitOf(`s_${p.name}`, p.width, bit, lang);
      };
      if (p.bits.every((b) => b.kind !== 'inout')) {
        conns.push(lang === 'verilog' ? `.${p.name}(s_${p.name})` : `${p.name} => s_${p.name}`);
      } else if (lang === 'verilog') {
        const bits = Array.from({ length: p.width }, (_, i) => actual(p.width - 1 - i));
        conns.push(`.${p.name}(${p.width > 1 ? `{${bits.join(', ')}}` : bits[0]})`);
      } else if (p.width > 1) {
        for (let i = 0; i < p.width; i++) conns.push(`${p.name}(${i}) => ${actual(i)}`);
      } else conns.push(`${p.name} => ${actual(0)}`);
    } else {
      conns.push(lang === 'verilog' ? `.${p.name}(s_${p.name})` : `${p.name} => s_${p.name}`);
    }
  }
  return conns;
}

function clockNet(plan: TopLevelPlan, p: DesignPortPlan): string {
  const k = plan.clocks[p.clock!];
  return k.halfPeriod > 0 ? `s_clock_${p.name}` : FPGA_CLOCK;
}

function clockComment(k: TopLevelPlan['clocks'][number], oscillatorHz: number): string {
  if (k.halfPeriod === 0) return `${k.port}: board clock ${formatHz(oscillatorHz)} directly`;
  return `${k.port}: ${formatHz(oscillatorHz)} / ${2 * k.halfPeriod} = ${formatHz(k.actualHz)} (asked ${formatHz(k.requestedHz)})`;
}

export function formatHz(hz: number): string {
  const f = (v: number) => String(Number(v.toPrecision(6)));
  if (hz >= 1e6) return `${f(hz / 1e6)} MHz`;
  if (hz >= 1e3) return `${f(hz / 1e3)} kHz`;
  return `${f(hz)} Hz`;
}

// --- Verilog ---------------------------------------------------------------------------------------------------

function topVerilog(plan: TopLevelPlan): string[] {
  const lang: HdlLang = 'verilog';
  const w = (width: number) => (width > 1 ? `[${width - 1}:0] ` : '');
  const out: string[] = [`module ${plan.name} (`];
  const ports = plan.ports.map((p) => `  ${p.dir === 'in' ? 'input' : p.dir === 'out' ? 'output' : 'inout'} wire ${w(p.width)}${p.name}`);
  out.push(ports.length ? ports.join(',\n') : '  // No FPGA pins in use', ');', '');

  const decls: string[] = [];
  for (const p of plan.designPorts) {
    if (p.clock !== undefined) {
      if (plan.clocks[p.clock].halfPeriod > 0) decls.push(`  wire s_clock_${p.name};`);
    } else if (p.dir !== 'inout' || p.bits.some((b) => b.kind !== 'inout')) decls.push(`  wire ${w(p.width)}s_${p.name};`);
  }
  for (const d of plan.drivers) for (const s of driverSignals(d)) decls.push(`  wire ${w(driverSignalWidth(d))}${s};`);
  if (decls.length) out.push('  // Design-side signals', ...decls, '');

  const adapt = adaptations(plan, lang);
  if (adapt.length) out.push('  // Signal adaptations (active-low pins are inverted here)', ...adapt, '');

  plan.clocks.forEach((k, i) => {
    out.push(`  // Clock ${clockComment(k, plan.oscillatorHz)}`);
    if (k.halfPeriod > 0) {
      out.push(
        `  LogisimClockDivider #(.HALF_PERIOD(${k.halfPeriod}), .COUNTER_BITS(${bitsFor(k.halfPeriod - 1)})) clock${i} (`,
        `    .fpgaGlobalClock(${FPGA_CLOCK}),`,
        `    .clockOut(s_clock_${k.port})`,
        '  );'
      );
    }
    out.push('');
  });

  const conns = designConnections(plan, lang);
  out.push('  // The design', `  ${plan.designName} dut (`, conns.map((x) => `    ${x}`).join(',\n'), '  );');

  for (const d of plan.drivers) {
    const inst = driverInstance(d, plan.oscillatorHz);
    out.push(
      '',
      `  // ${d.kind === 'scanning' ? 'Multiplexed 7-segment display' : 'LED array'} ${d.io.label ?? ''}`.trimEnd(),
      ...driverInputs(d, lang),
      `  ${driverModule(d)} #(${inst.generics.map(([k, v]) => `.${k}(${v})`).join(', ')}) ${d.kind === 'scanning' ? 'sevenSegScan' : 'array'}${d.id} (`,
      inst.ports.map(([k, v]) => `    .${k}(${v ?? ''})`).join(',\n'),
      '  );'
    );
  }
  out.push('endmodule');
  return out;
}

// --- VHDL ------------------------------------------------------------------------------------------------------

function topVhdl(plan: TopLevelPlan): string[] {
  const lang: HdlLang = 'vhdl';
  const out: string[] = ['library IEEE;', 'use IEEE.STD_LOGIC_1164.ALL;', 'use IEEE.NUMERIC_STD.ALL;', '', `entity ${plan.name} is`];
  if (plan.ports.length) out.push('  port (', plan.ports.map((p) => `    ${p.name} : ${p.dir} ${vecType(p.width)}`).join(';\n'), '  );');
  out.push(`end entity ${plan.name};`, '', `architecture Behavioral of ${plan.name} is`);
  for (const p of plan.designPorts) {
    if (p.clock !== undefined) {
      if (plan.clocks[p.clock].halfPeriod > 0) out.push(`  signal s_clock_${p.name} : std_logic;`);
    } else if (p.dir !== 'inout' || p.bits.some((b) => b.kind !== 'inout')) out.push(`  signal s_${p.name} : ${vecType(p.width)};`);
  }
  for (const d of plan.drivers) for (const s of driverSignals(d)) out.push(`  signal ${s} : std_logic_vector(${driverSignalWidth(d) - 1} downto 0);`);
  out.push('begin');

  const adapt = adaptations(plan, lang);
  if (adapt.length) out.push('  -- Signal adaptations (active-low pins are inverted here)', ...adapt, '');

  plan.clocks.forEach((k, i) => {
    out.push(`  -- Clock ${clockComment(k, plan.oscillatorHz)}`);
    if (k.halfPeriod > 0) {
      out.push(
        `  clock${i} : entity work.LogisimClockDivider`,
        `    generic map (HALF_PERIOD => ${k.halfPeriod}, COUNTER_BITS => ${bitsFor(k.halfPeriod - 1)})`,
        `    port map (fpgaGlobalClock => ${FPGA_CLOCK}, clockOut => s_clock_${k.port});`
      );
    }
    out.push('');
  });

  const conns = designConnections(plan, lang);
  out.push('  -- The design', `  dut : entity work.${plan.designName}`);
  if (conns.length) out.push('    port map (', conns.map((x) => `      ${x}`).join(',\n'), '    );');
  else out.push('    ;');

  for (const d of plan.drivers) {
    const inst = driverInstance(d, plan.oscillatorHz);
    out.push(
      '',
      `  -- ${d.kind === 'scanning' ? 'Multiplexed 7-segment display' : 'LED array'} ${d.io.label ?? ''}`.trimEnd(),
      ...driverInputs(d, lang),
      `  ${d.kind === 'scanning' ? 'sevenSegScan' : 'array'}${d.id} : entity work.${driverModule(d)}`,
      `    generic map (${inst.generics.map(([k, v]) => `${k} => ${v}`).join(', ')})`,
      '    port map (',
      inst.ports.map(([k, v]) => `      ${k} => ${v ?? 'open'}`).join(',\n'),
      '    );'
    );
  }
  out.push('end architecture Behavioral;');
  return out;
}
