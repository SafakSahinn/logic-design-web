// Pin constraint files of a top-level plan, one writer per tool chain, as Logisim-evolution writes them
// (fpga/download/VivadoDownload, XilinxDownload, AlteraDownload, OpenFpgaDownload): the board oscillator with its
// period, then every FPGA pin with its IO standard, pull and drive. The LED array / multiplexed display drivers'
// pins are in the plan already.
import type { BoardDefinition, BoardVendor, IoStandard, PullBehavior } from '../board/model';
import type { PlacedPin, TopLevelPlan } from './plan';
import { FPGA_CLOCK } from './plan';
import type { HdlLang } from './drivers';

export interface ConstraintFile {
  fileName: string;
  text: string;
}

export interface ConstraintOptions {
  /** Name of the top-level file and the design file, for the tools that list sources (Quartus) */
  files: { name: string; lang: HdlLang }[];
  /** Comment lines for the file header */
  header?: string[];
}

/** File extension of a vendor's constraints */
export const CONSTRAINT_EXTENSION: Record<BoardVendor, string> = { vivado: 'xdc', xilinx: 'ucf', altera: 'qsf', openFpga: 'lpf' };

/** Oscillator frequency as evo writes it ("50 MHz", "12 kHz", or plain Hz) */
export function clockFrequencyText(hz: number): string {
  if (hz % 1_000_000 === 0) return `${hz / 1_000_000} MHz`;
  if (hz % 1000 === 0) return `${hz / 1000} kHz`;
  return String(hz);
}

/** Port (bit) as the vendor names it: ISE writes bus bits with <>, the others with [] */
function portRef(p: PlacedPin, vendor: BoardVendor): string {
  if (p.bit === undefined) return p.port;
  return vendor === 'xilinx' ? `${p.port}<${p.bit}>` : `${p.port}[${p.bit}]`;
}

const pullName = (pull: PullBehavior) => (pull === 'pullUp' ? 'PULLUP' : pull === 'pullDown' ? 'PULLDOWN' : '');

/** Quartus names of the IO standards */
const QUARTUS_IO: Record<Exclude<IoStandard, 'default'>, string> = {
  LVCMOS12: '1.2 V',
  LVCMOS15: '1.5 V',
  LVCMOS18: '1.8 V',
  LVCMOS25: '2.5 V',
  LVCMOS33: '3.3-V LVCMOS',
  LVTTL: '3.3-V LVTTL',
};

export function writeConstraints(plan: TopLevelPlan, board: BoardDefinition, options: ConstraintOptions): ConstraintFile {
  const vendor = board.fpga.vendor;
  const fileName = `${plan.name}.${CONSTRAINT_EXTENSION[vendor]}`;
  // Every one of the four formats takes # comments
  const comment = '#';
  const head = [
    `${comment} Pin constraints generated by LogicDesign Studio`,
    `${comment} Board: ${board.name} (${board.fpga.family} ${board.fpga.part} ${board.fpga.package})`,
    `${comment} Top level: ${plan.name}`,
    ...(options.header ?? []).map((h) => (h ? `${comment} ${h}` : comment)),
    '',
  ];
  const body =
    vendor === 'vivado' ? vivado(plan) : vendor === 'xilinx' ? ise(plan) : vendor === 'altera' ? quartus(plan, board, options) : openFpga(plan);
  return { fileName, text: [...head, ...body, ''].join('\n') };
}

// --- Vivado .xdc -----------------------------------------------------------------------------------------------

function vivado(plan: TopLevelPlan): string[] {
  const out: string[] = [];
  for (const p of plan.pins) {
    const ref = `[get_ports {${portRef(p, 'vivado')}}]`;
    out.push(`set_property PACKAGE_PIN ${p.fpgaPin} ${ref}`);
    if (p.ioStandard !== 'default') out.push(`    set_property IOSTANDARD ${p.ioStandard} ${ref}`);
    if (p.pull !== 'float') out.push(`    set_property ${pullName(p.pull)} TRUE ${ref}`);
    if (p.drive) out.push(`    set_property DRIVE ${p.drive} ${ref}`);
    if (p.clock) {
      const period = 1e9 / plan.oscillatorHz;
      out.push(`    create_clock -add -name sys_clk_pin -period ${period.toFixed(2)} -waveform {0 ${(period / 2).toFixed(2)}} ${ref}`, '');
    }
  }
  return out;
}

// --- Xilinx ISE .ucf -------------------------------------------------------------------------------------------

function ise(plan: TopLevelPlan): string[] {
  const out: string[] = [];
  for (const p of plan.pins) {
    const parts = [`NET "${portRef(p, 'xilinx')}" LOC = "${p.fpgaPin}"`];
    if (p.pull !== 'float') parts.push(pullName(p.pull));
    if (p.drive) parts.push(`DRIVE = ${p.drive}`);
    if (p.ioStandard !== 'default') parts.push(`IOSTANDARD = ${p.ioStandard}`);
    out.push(`${parts.join(' | ')} ;`);
    if (p.clock) {
      out.push(
        `NET "${FPGA_CLOCK}" TNM_NET = "${FPGA_CLOCK}" ;`,
        `TIMESPEC "TS_${FPGA_CLOCK}" = PERIOD "${FPGA_CLOCK}" ${clockFrequencyText(plan.oscillatorHz)} HIGH 50 % ;`,
        ''
      );
    }
  }
  return out;
}

// --- Intel / Altera Quartus .qsf -------------------------------------------------------------------------------

function quartus(plan: TopLevelPlan, board: BoardDefinition, options: ConstraintOptions): string[] {
  const f = board.fpga;
  const g = 'set_global_assignment -name';
  const pkg = f.package.trim().split(/\s+/);
  const unused = f.unusedPull === 'pullUp' ? 'PULLUP' : f.unusedPull === 'pullDown' ? 'PULLDOWN' : 'TRI-STATED';
  const out: string[] = [
    `${g} FAMILY "${f.family}"`,
    `${g} DEVICE ${f.part}`,
    ...(pkg.length === 2 ? [`${g} DEVICE_FILTER_PACKAGE ${pkg[0]}`, `${g} DEVICE_FILTER_PIN_COUNT ${pkg[1]}`] : []),
    `${g} TOP_LEVEL_ENTITY ${plan.name}`,
    `${g} RESERVE_ALL_UNUSED_PINS "AS INPUT ${unused}"`,
    ...(plan.usesClock ? [`${g} FMAX_REQUIREMENT "${clockFrequencyText(plan.oscillatorHz)}"`] : []),
    `${g} RESERVE_NCEO_AFTER_CONFIGURATION "USE AS REGULAR IO"`,
    `${g} CYCLONEII_RESERVE_NCEO_AFTER_CONFIGURATION "USE AS REGULAR IO"`,
    ...options.files.map((file) => `${g} ${file.lang === 'vhdl' ? 'VHDL_FILE' : 'VERILOG_FILE'} "${file.name}"`),
    '',
  ];
  for (const p of plan.pins) {
    const ref = portRef(p, 'altera');
    out.push(`set_location_assignment ${p.fpgaPin} -to ${ref}`);
    if (p.ioStandard !== 'default') out.push(`set_instance_assignment -name IO_STANDARD "${QUARTUS_IO[p.ioStandard]}" -to ${ref}`);
    // Quartus has a weak pull-up only (evo writes nothing for a pull-down either)
    if (p.pull === 'pullUp') out.push(`set_instance_assignment -name WEAK_PULL_UP_RESISTOR ON -to ${ref}`);
    if (p.drive) out.push(`set_instance_assignment -name CURRENT_STRENGTH_NEW "${p.drive}MA" -to ${ref}`);
  }
  return out;
}

// --- openFPGA (Lattice ECP5, nextpnr) .lpf ---------------------------------------------------------------------

function openFpga(plan: TopLevelPlan): string[] {
  const out: string[] = ['BLOCK RESETPATHS;', 'BLOCK ASYNCPATHS;', ''];
  for (const p of plan.pins) {
    const ref = portRef(p, 'openFpga');
    out.push(`LOCATE COMP "${ref}" SITE "${p.fpgaPin.toUpperCase()}";`);
    const pull = p.pull === 'pullUp' ? 'UP' : p.pull === 'pullDown' ? 'DOWN' : null;
    const io = p.ioStandard === 'default' ? null : p.ioStandard;
    const drive = p.drive ? String(p.drive) : null;
    if (pull || io || drive) out.push(`IOBUF PORT "${ref}" PULLMODE=${pull ?? 'NONE'}${io ? ` IO_TYPE=${io}` : ''}${drive ? ` DRIVE=${drive}` : ''};`);
    if (p.clock) out.push(`FREQUENCY PORT "${FPGA_CLOCK}" ${clockFrequencyText(plan.oscillatorHz).toUpperCase()};`, '');
  }
  return out;
}
